// ─── Express-style → Elysia adapter (v2: POST + body support) ────────────────
// Key change: req.query now auto-merges c.body (JSON) on POST requests.
// This means ALL 140+ existing handlers work unchanged for BOTH GET and POST.
// On POST, body params override query params with the same name.
function adapt(feature) {
    const run = feature.handler
    return async (c) => {
        let status = 200
        let response = null

        // Merge query + body into a single req.query.
        // On GET: req.query = c.query only (no body).
        // On POST: req.query = { ...c.query, ...c.body } — body overrides query.
        // This way, handlers that read from req.query work for both GET and POST.
        const body = (c.body && typeof c.body === "object" && !Buffer.isBuffer(c.body)) ? c.body : {}
        const mergedQuery = { ...c.query, ...body }

        const req = {
            query: mergedQuery,
            body: body,
            headers: c.headers,
            get: (h) => c.headers[h.toLowerCase()],
        }

        const res = {
            status(code) { status = code; return this },
            json(obj) {
                response = new Response(JSON.stringify(obj), {
                    status,
                    headers: {
                        "content-type": "application/json; charset=utf-8",
                        "access-control-allow-origin": "*",
                    },
                })
                return response
            },
            send(body) {
                const isBuf = Buffer.isBuffer(body)
                response = new Response(body, {
                    status,
                    headers: {
                        ...(isBuf
                            ? { "content-type": "application/octet-stream" }
                            : { "content-type": "text/html; charset=utf-8" }),
                        "access-control-allow-origin": "*",
                    },
                })
                return response
            },
            end(body) {
                response = new Response(body ?? null, {
                    status,
                    headers: { "access-control-allow-origin": "*" },
                })
                return response
            },
        }

        try {
            await run(req, res)
            if (response) return response
            return new Response(null, { status, headers: { "access-control-allow-origin": "*" } })
        } catch (e) {
            return new Response(
                JSON.stringify({ ok: false, error: e?.message || String(e) }),
                { status: 500, headers: { "content-type": "application/json; charset=utf-8", "access-control-allow-origin": "*" } },
            )
        }
    }
}

