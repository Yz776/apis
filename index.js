// ─── Register every feature route (GET + POST auto-registration) ─────────────
// v2 change: For every GET endpoint, we also register a POST version.
// This means ALL endpoints accept both GET (query params) and POST (JSON body).
// The adapt() function merges body into req.query, so handlers work unchanged.
for (const f of features) {
    const {
        method, path: routePath, auth,
        tags = [], summary, description,
        parameters, requestBody, responses,
    } = f.route

    const verb = method.toLowerCase()
    if (typeof app[verb] !== "function") {
        console.warn(`[skip] unsupported HTTP method "${method}" for ${routePath}`)
        continue
    }

    const handler = adapt(f)
    const enforceAuth = ENABLE_AUTH && auth

    // Build OpenAPI detail from the feature file metadata
    const buildDetail = (forPost = false) => {
        const detail = {
            tags,
            ...(summary && { summary: forPost ? `${summary} (POST)` : summary }),
            ...(description && { description }),
            ...(enforceAuth && { security: [{ ApiKeyAuth: [] }] }),
        }

        if (!forPost && parameters) {
            detail.params = parameters.filter(p => p.in === "path")
            detail.query = parameters.filter(p => p.in === "query")
        }

        if (forPost && parameters) {
            // For POST, build a requestBody schema from the query parameters
            const queryParams = parameters.filter(p => p.in === "query")
            if (queryParams.length > 0) {
                const properties = {}
                const required = []
                for (const p of queryParams) {
                    properties[p.name] = {
                        ...(p.schema || { type: "string" }),
                        ...(p.description && { description: p.description }),
                    }
                    if (p.required) required.push(p.name)
                }
                detail.body = {
                    type: "object",
                    properties,
                    ...(required.length > 0 && { required }),
                }
            }
        }

        if (forPost && requestBody) {
            detail.body = requestBody
        }

        if (responses) {
            detail.response = Object.fromEntries(
                Object.entries(responses).map(([code, r]) => [
                    code,
                    r?.content?.["application/json"]?.schema ?? {},
                ]),
            )
        }

        return detail
    }

    // Register the original method (usually GET)
    app[verb](routePath, handler, {
        detail: buildDetail(false),
        ...(enforceAuth && {
            beforeHandle: (c) => {
                const key = c.headers["x-api-key"]
                if (!key || key !== API_KEY) {
                    return new Response(
                        JSON.stringify({ ok: false, error: "API key tidak valid" }),
                        { status: 401, headers: { "content-type": "application/json; charset=utf-8", "access-control-allow-origin": "*" } },
                    )
                }
            },
        }),
    })

    // Auto-register POST for every GET endpoint
    if (verb === "get") {
        app.post(routePath, handler, {
            detail: buildDetail(true),
            ...(enforceAuth && {
                beforeHandle: (c) => {
                    const key = c.headers["x-api-key"]
                    if (!key || key !== API_KEY) {
                        return new Response(
                            JSON.stringify({ ok: false, error: "API key tidak valid" }),
                            { status: 401, headers: { "content-type": "application/json; charset=utf-8", "access-control-allow-origin": "*" } },
                        )
                    }
                },
            }),
        })
        console.log(`  [dual] ${routePath} → GET + POST`)
    }
}

